/**
 * ล้างของค้างในเครื่องให้เอง — ไม่ต้องให้คนไปกดล้างแคชทีละเครื่อง
 *
 * เจ้าของถาม 14 ก.ย. 2026: "เครื่องที่ค้างอยู่ คุณก็เคลียร์สิ ไม่ได้หรอ" — ได้ครับ
 * ทำตรงนี้: พอเครื่องไหนโหลดโค้ดชุดใหม่ได้สำเร็จ โค้ดชุดนี้จะล้างของเก่าทิ้งเองทันที
 *
 * ล้างสองอย่างที่ทำให้ของเก่าค้าง:
 *   1. service worker รุ่นเก่าที่เคยติดมากับหลังร้านสมัยยังเป็น PWA — ตัวนี้ดักทุกคำขอ
 *      แล้วตอบจากแคชของมันเอง ทำให้ตั้ง header อะไรก็ไม่มีผล
 *   2. Cache Storage ทุกก้อนที่ service worker ตัวนั้นเก็บไว้
 *
 * ★ รีโหลดหนึ่งครั้งหลังล้าง ★ หน้าที่กำลังเปิดอยู่ตอนนั้นยังเป็นไฟล์ชุดที่ service worker
 * เสิร์ฟมาก่อนล้าง — ถ้าไม่รีโหลด คนจะยังเห็นรุ่นเก่าทั้งที่ล้างไปแล้ว และจะงงกว่าเดิม
 * รีโหลดเฉพาะตอนที่ "เจอของค้างจริง" เท่านั้น เครื่องปกติจะไม่โดนรีโหลดมั่ว ๆ
 *
 * ★ ทำไมยังต้องมีคนเปิดหน้าก่อน ★ เครื่องที่ไม่เคยเปิดเว็บอีกเลยเราไปแตะไม่ได้ ไม่มีใคร
 * สั่งเครื่องที่ไม่ได้ติดต่อเรากลับมาได้ — แต่พอเปิดเมื่อไหร่ก็จะสะอาดในรอบเดียว
 */
export async function purgeStaleCaches(): Promise<void> {
  let removed = false;

  try {
    if ('serviceWorker' in navigator) {
      const regs = await navigator.serviceWorker.getRegistrations();
      for (const r of regs) {
        /* ★ ยกเลิกทุกตัวที่เจอ ★ หลังร้านไม่ได้ใช้ service worker แล้ว ตัวที่ยังอยู่คือ
           ของเก่าที่ค้างมาทั้งนั้น ไม่ต้องแยกว่าตัวไหนคือตัวไหน */
        if (await r.unregister()) removed = true;
      }
    }
  } catch {
    /* บางเบราว์เซอร์/โหมดส่วนตัวปิดไว้ — ไม่ใช่เรื่องที่ต้องหยุดการเปิดหน้า */
  }

  try {
    if ('caches' in window) {
      const keys = await caches.keys();
      for (const k of keys) {
        if (await caches.delete(k)) removed = true;
      }
    }
  } catch {
    /* เช่นเดียวกัน */
  }

  if (!removed) return;

  /* กันรีโหลดวน: ถ้าเพิ่งรีโหลดเพราะเรื่องนี้ไปเมื่อกี้ ไม่ทำซ้ำอีก แม้จะยังเจอของค้าง
     (เครื่องที่ล้างไม่ออกจริง ๆ ต้องให้คนจัดการเอง ดีกว่าติดวนรีโหลดจนใช้งานไม่ได้) */
  try {
    if (sessionStorage.getItem('ofu-purged') === '1') return;
    sessionStorage.setItem('ofu-purged', '1');
  } catch {
    return;
  }
  window.location.reload();
}
